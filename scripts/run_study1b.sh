#!/usr/bin/env bash
# Study 1b (run A): the Study 1 recipe trained on object-centred square crops instead
# of letterboxed tiles. Protocol: docs/study1b_protocol.md. Every stage is resumable.
#
#   scripts/run_study1b.sh build       # ~5 min, crop the 423 Study 1 composites (needs .venv-eval)
#   scripts/run_study1b.sh train c1    # ~30 min per replicate (c1, c2, c3)
#   scripts/run_study1b.sh main        # ~7 h, 42 prompts x 4 seeds x (base + c1, c2, c3)
#   scripts/run_study1b.sh check-base  # base images must equal Study 1's byte for byte
#   scripts/run_study1b.sh controls    # ~5 min, metric controls on the cropped real holdout
#   scripts/run_study1b.sh metrics     # ~30 min, score the main run (needs .venv-eval)
#   scripts/run_study1b.sh gpu         # train c1-c3, main, check-base, in that order
#
# Do not edit this file while a stage is running: bash reads it as it goes.
set -euo pipefail
cd "$(dirname "$0")/.."

GEN=(.venv/bin/python -m evaluation.generate_pairs --quantization 8bit --resume)
OUT=evaluation/results/study1b_8bit
CROP=training/study1b_crop
ckpt() { echo "output/study1b_crop_$1/study1b_crop_$1.safetensors"; }

require_committed_protocol() {
  if ! git ls-files --error-unmatch docs/study1b_protocol.md >/dev/null 2>&1 \
    || ! git diff --quiet HEAD -- docs/study1b_protocol.md configs/study1b_crop_c*.yaml; then
    echo "Commit docs/study1b_protocol.md and the configs before training or generating"; exit 1
  fi
}

train() {
  local rep=$1
  if [ -f "$(ckpt "$rep")" ]; then echo "$(ckpt "$rep") exists; not retraining"; return; fi
  require_committed_protocol
  WANDB_MODE=offline ../ai-toolkit/.venv/bin/python ../ai-toolkit/run.py \
    "configs/study1b_crop_$rep.yaml"
}

case "${1:-}" in
  build)
    .venv-eval/bin/python -m src.crop_composites --output-dir "$CROP"
    ;;
  train)
    case "${2:-}" in c1 | c2 | c3) train "$2" ;; *) echo "train c1|c2|c3"; exit 2 ;; esac
    ;;
  main)
    require_committed_protocol
    "${GEN[@]}" --prompts evaluation/prompts_holdout.jsonl --seeds 1001 1002 1003 1004 \
      --output-dir "$OUT/main" \
      --arm "c1=$(ckpt c1)" --arm "c2=$(ckpt c2)" --arm "c3=$(ckpt c3)"
    ;;
  check-base)
    .venv/bin/python - "$OUT/main/generation_manifest.jsonl" \
      evaluation/results/study1_8bit/main/generation_manifest.jsonl <<'EOF'
import json, sys
def base(path):
    rows = [json.loads(line) for line in open(path)]
    return {(r["prompt_id"], r["seed"]): r["output_sha256"] for r in rows if r["condition"] == "base"}
new, old = base(sys.argv[1]), base(sys.argv[2])
same = sum(new.get(k) == v for k, v in old.items())
print(f"base images identical to Study 1: {same}/{len(old)} (new run has {len(new)})")
sys.exit(0 if same == len(old) == len(new) else 1)
EOF
    ;;
  controls)
    .venv-eval/bin/python -m evaluation.controls build --split-root "$CROP" \
      --output-dir evaluation/results/controls_crop
    .venv-eval/bin/python -m evaluation.metrics.run_metrics \
      --grids evaluation/results/controls_crop/grids.jsonl --output-dir results/metrics/controls_crop
    .venv-eval/bin/python -m evaluation.controls check --metrics-dir results/metrics/controls_crop
    ;;
  metrics)
    .venv-eval/bin/python -m evaluation.metrics.run_metrics \
      --grids "$OUT/main/generation_manifest.jsonl" --output-dir results/metrics/study1b_main
    ;;
  gpu)
    for rep in c1 c2 c3; do train "$rep"; done
    "$0" main
    "$0" check-base
    ;;
  *)
    sed -n '2,13p' "$0"
    exit 2
    ;;
esac
